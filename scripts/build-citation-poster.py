"""Builds public/terminal/citation/poster.webp from the source teaser artwork.

The Citation source poster (Oct 2026) was generated by editing the earlier
Proximize poster, so it already carries the site's own "SP / PORTFOLIO
SYSTEM" enamel badge in the platform slot and no real platform marks or
third-party disclaimer: nothing needs erasing (the Proximize-era version of
this script stripped a PlayStation mark). This script only normalises the
canvas to the 1085x1450 the terminal expects (POSTER_ASPECT in
content/citation.ts, and the frame boxes in build-citation-frames.py) and
encodes WebP q82.

The source PNG is deliberately not committed; pass its path as argv[1].
Requires Pillow, which is NOT a project dependency. Run it from a throwaway
venv:

    python3 -m venv /tmp/poster-venv
    /tmp/poster-venv/bin/pip install Pillow
    /tmp/poster-venv/bin/python scripts/build-citation-poster.py ~/path/to/source.png
"""

import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "public" / "terminal" / "citation" / "poster.webp"
SIZE = (1085, 1450)


def main():
    if len(sys.argv) < 2:
        sys.exit("usage: build-citation-poster.py <source.png>  (see module docstring)")

    src = Image.open(sys.argv[1]).convert("RGB")
    if src.size != SIZE:
        src = src.resize(SIZE, Image.LANCZOS)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    src.save(OUT, "WEBP", quality=82, method=6)
    print(f"wrote {OUT.relative_to(ROOT)}  {SIZE[0]}x{SIZE[1]}  {OUT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
